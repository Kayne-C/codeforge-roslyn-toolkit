using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CodeForge
{
    [Generator(LanguageNames.CSharp)]
    public sealed class ArchitectureAttributesGenerator : IIncrementalGenerator
    {
        private const string Source = @"// <auto-generated/>
#nullable enable
namespace CodeForge
{
    [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, Inherited = false, AllowMultiple = true)]
    internal sealed class ForbidDependencyAttribute : global::System.Attribute
    {
        public ForbidDependencyAttribute(string from, string to)
        {
            From = from;
            To = to;
        }

        public string From { get; }

        public string To { get; }
    }
}
";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx => ctx.AddSource("ForbidDependencyAttribute.g.cs", SourceText.From(Source, Encoding.UTF8)));
        }
    }
}
