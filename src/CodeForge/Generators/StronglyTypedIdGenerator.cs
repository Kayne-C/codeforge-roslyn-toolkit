using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CodeForge
{
    [Generator(LanguageNames.CSharp)]
    public sealed class StronglyTypedIdGenerator : IIncrementalGenerator
    {
        internal const string AttributeName = "CodeForge.StronglyTypedIdAttribute";

        private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace CodeForge
{
    [global::System.AttributeUsage(global::System.AttributeTargets.Struct, Inherited = false, AllowMultiple = false)]
    internal sealed class StronglyTypedIdAttribute : global::System.Attribute
    {
        public StronglyTypedIdAttribute()
        {
            BackingType = typeof(global::System.Guid);
        }

        public StronglyTypedIdAttribute(global::System.Type backingType)
        {
            BackingType = backingType;
        }

        public global::System.Type BackingType { get; }
    }
}
";

        internal enum Backing
        {
            Guid,
            Int32,
            Int64,
            String,
        }

        internal sealed record IdModel(
            string? Namespace,
            string Name,
            string Accessibility,
            Backing Backing,
            bool HasJson,
            bool HasParsable,
            EquatableArray<DiagnosticInfo> Diagnostics);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx => ctx.AddSource("StronglyTypedIdAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

            var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (ctx, ct) => Transform(ctx, ct));

            context.RegisterSourceOutput(models, static (spc, model) =>
            {
                foreach (var d in model.Diagnostics)
                {
                    spc.ReportDiagnostic(d.ToDiagnostic());
                }

                if (model.Diagnostics.Length > 0)
                {
                    return;
                }

                spc.AddSource(HintName(model), SourceText.From(Emit(model), Encoding.UTF8));
            });
        }

        private static string HintName(IdModel model) => (model.Namespace is null ? model.Name : model.Namespace + "." + model.Name) + ".StronglyTypedId.g.cs";

        private static IdModel Transform(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            var symbol = (INamedTypeSymbol)ctx.TargetSymbol;
            var syntax = (TypeDeclarationSyntax)ctx.TargetNode;
            var diagnostics = new List<DiagnosticInfo>();
            var location = syntax.Identifier.GetLocation();

            if (symbol.TypeKind != TypeKind.Struct || !syntax.Modifiers.Any(m => m.Text == "partial"))
            {
                diagnostics.Add(DiagnosticInfo.Create("CFG001", $"'{symbol.Name}' must be declared as a partial struct to be a strongly typed id.", location));
            }
            else if (symbol.ContainingType != null)
            {
                diagnostics.Add(DiagnosticInfo.Create("CFG001", $"'{symbol.Name}' must be a top-level type; nested strongly typed ids are not supported.", location));
            }

            var backing = Backing.Guid;
            var attribute = ctx.Attributes[0];
            if (attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is ITypeSymbol type)
            {
                switch (type.SpecialType)
                {
                    case SpecialType.System_Int32:
                        backing = Backing.Int32;
                        break;
                    case SpecialType.System_Int64:
                        backing = Backing.Int64;
                        break;
                    case SpecialType.System_String:
                        backing = Backing.String;
                        break;
                    default:
                        if (type.ToDisplayString() != "System.Guid")
                        {
                            diagnostics.Add(DiagnosticInfo.Create("CFG002", $"'{type.ToDisplayString()}' is not supported; use Guid, int, long or string.", location));
                        }

                        break;
                }
            }

            var compilation = ctx.SemanticModel.Compilation;
            return new IdModel(
                symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString(),
                symbol.Name,
                symbol.DeclaredAccessibility == Accessibility.Public ? "public" : "internal",
                backing,
                compilation.GetTypeByMetadataName("System.Text.Json.Serialization.JsonConverter`1") != null,
                compilation.GetTypeByMetadataName("System.IParsable`1") != null,
                new EquatableArray<DiagnosticInfo>(diagnostics));
        }

        private static string Emit(IdModel m)
        {
            var t = m.Name;
            var (clr, isNumeric) = m.Backing switch
            {
                Backing.Guid => ("global::System.Guid", false),
                Backing.Int32 => ("int", true),
                Backing.Int64 => ("long", true),
                _ => ("string", false),
            };

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            if (m.Namespace != null)
            {
                sb.AppendLine("namespace " + m.Namespace);
                sb.AppendLine("{");
            }

            if (m.HasJson)
            {
                sb.AppendLine($"[global::System.Text.Json.Serialization.JsonConverter(typeof({t}.StronglyTypedIdJsonConverter))]");
            }

            sb.AppendLine($"[global::System.ComponentModel.TypeConverter(typeof({t}.StronglyTypedIdTypeConverter))]");
            var interfaces = $"global::System.IEquatable<{t}>, global::System.IComparable<{t}>" + (m.HasParsable ? $", global::System.IParsable<{t}>" : string.Empty);
            sb.AppendLine($"{m.Accessibility} readonly partial struct {t} : {interfaces}");
            sb.AppendLine("{");

            sb.AppendLine($"    public {t}({clr} value)");
            sb.AppendLine("    {");
            if (m.Backing == Backing.String)
            {
                sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(value);");
            }

            sb.AppendLine("        Value = value;");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine($"    public {clr} Value {{ get; }}");
            sb.AppendLine();

            if (m.Backing == Backing.Guid)
            {
                sb.AppendLine($"    public static {t} New() => new {t}(global::System.Guid.NewGuid());");
                sb.AppendLine();
                sb.AppendLine($"    public static {t} Empty => default;");
                sb.AppendLine();
                sb.AppendLine("    public bool IsEmpty => Value == global::System.Guid.Empty;");
                sb.AppendLine();
            }

            sb.AppendLine($"    public static {t} From({clr} value) => new {t}(value);");
            sb.AppendLine();
            sb.AppendLine($"    public static explicit operator {t}({clr} value) => new {t}(value);");
            sb.AppendLine();
            sb.AppendLine($"    public static explicit operator {clr}({t} id) => id.Value;");
            sb.AppendLine();

            if (m.Backing == Backing.String)
            {
                sb.AppendLine($"    public bool Equals({t} other) => string.Equals(Value ?? string.Empty, other.Value ?? string.Empty, global::System.StringComparison.Ordinal);");
                sb.AppendLine("    public override int GetHashCode() => (Value ?? string.Empty).GetHashCode();");
                sb.AppendLine($"    public int CompareTo({t} other) => string.CompareOrdinal(Value ?? string.Empty, other.Value ?? string.Empty);");
                sb.AppendLine("    public override string ToString() => Value ?? string.Empty;");
            }
            else
            {
                sb.AppendLine($"    public bool Equals({t} other) => Value == other.Value;");
                sb.AppendLine("    public override int GetHashCode() => Value.GetHashCode();");
                sb.AppendLine($"    public int CompareTo({t} other) => Value.CompareTo(other.Value);");
                sb.AppendLine(isNumeric ? "    public override string ToString() => Value.ToString(global::System.Globalization.CultureInfo.InvariantCulture);" : "    public override string ToString() => Value.ToString();");
            }

            sb.AppendLine($"    public override bool Equals(object? obj) => obj is {t} other && Equals(other);");
            sb.AppendLine($"    public static bool operator ==({t} left, {t} right) => left.Equals(right);");
            sb.AppendLine($"    public static bool operator !=({t} left, {t} right) => !left.Equals(right);");
            sb.AppendLine($"    public static bool operator <({t} left, {t} right) => left.CompareTo(right) < 0;");
            sb.AppendLine($"    public static bool operator <=({t} left, {t} right) => left.CompareTo(right) <= 0;");
            sb.AppendLine($"    public static bool operator >({t} left, {t} right) => left.CompareTo(right) > 0;");
            sb.AppendLine($"    public static bool operator >=({t} left, {t} right) => left.CompareTo(right) >= 0;");
            sb.AppendLine();

            sb.AppendLine($"    public static {t} Parse(string s, global::System.IFormatProvider? provider)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (TryParse(s, provider, out var result))");
            sb.AppendLine("        {");
            sb.AppendLine("            return result;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        throw new global::System.FormatException($\"'{{s}}' is not a valid {t}.\");");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine($"    public static bool TryParse(string? s, global::System.IFormatProvider? provider, out {t} result)");
            sb.AppendLine("    {");
            switch (m.Backing)
            {
                case Backing.Guid:
                    sb.AppendLine("        if (global::System.Guid.TryParse(s, out var value))");
                    break;
                case Backing.Int32:
                    sb.AppendLine("        if (int.TryParse(s, global::System.Globalization.NumberStyles.Integer, provider, out var value))");
                    break;
                case Backing.Int64:
                    sb.AppendLine("        if (long.TryParse(s, global::System.Globalization.NumberStyles.Integer, provider, out var value))");
                    break;
                default:
                    sb.AppendLine("        if (s is { } value)");
                    break;
            }

            sb.AppendLine("        {");
            sb.AppendLine($"            result = new {t}(value);");
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        result = default;");
            sb.AppendLine("        return false;");
            sb.AppendLine("    }");
            sb.AppendLine();

            if (m.HasJson)
            {
                var (read, write, readKey) = m.Backing switch
                {
                    Backing.Guid => ("reader.GetGuid()", "writer.WriteStringValue(value.Value)", "global::System.Guid.Parse(reader.GetString()!)"),
                    Backing.Int32 => ("reader.GetInt32()", "writer.WriteNumberValue(value.Value)", "int.Parse(reader.GetString()!, global::System.Globalization.CultureInfo.InvariantCulture)"),
                    Backing.Int64 => ("reader.GetInt64()", "writer.WriteNumberValue(value.Value)", "long.Parse(reader.GetString()!, global::System.Globalization.CultureInfo.InvariantCulture)"),
                    _ => ("reader.GetString()!", "writer.WriteStringValue(value.Value)", "reader.GetString()!"),
                };

                sb.AppendLine($"    private sealed class StronglyTypedIdJsonConverter : global::System.Text.Json.Serialization.JsonConverter<{t}>");
                sb.AppendLine("    {");
                sb.AppendLine($"        public override {t} Read(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options) => new {t}({read});");
                sb.AppendLine();
                sb.AppendLine($"        public override void Write(global::System.Text.Json.Utf8JsonWriter writer, {t} value, global::System.Text.Json.JsonSerializerOptions options) => {write};");
                sb.AppendLine();
                sb.AppendLine($"        public override {t} ReadAsPropertyName(ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options) => new {t}({readKey});");
                sb.AppendLine();
                sb.AppendLine($"        public override void WriteAsPropertyName(global::System.Text.Json.Utf8JsonWriter writer, {t} value, global::System.Text.Json.JsonSerializerOptions options) => writer.WritePropertyName(value.ToString());");
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            sb.AppendLine("    private sealed class StronglyTypedIdTypeConverter : global::System.ComponentModel.TypeConverter");
            sb.AppendLine("    {");
            sb.AppendLine("        public override bool CanConvertFrom(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Type sourceType)");
            sb.AppendLine("            => sourceType == typeof(string) || base.CanConvertFrom(context, sourceType);");
            sb.AppendLine();
            sb.AppendLine("        public override object? ConvertFrom(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Globalization.CultureInfo? culture, object value)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (value is string text)");
            sb.AppendLine("            {");
            sb.AppendLine("                return Parse(text, culture);");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            return base.ConvertFrom(context, culture, value);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        public override bool CanConvertTo(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Type? destinationType)");
            sb.AppendLine("            => destinationType == typeof(string) || base.CanConvertTo(context, destinationType);");
            sb.AppendLine();
            sb.AppendLine("        public override object? ConvertTo(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Globalization.CultureInfo? culture, object? value, global::System.Type destinationType)");
            sb.AppendLine("        {");
            sb.AppendLine($"            if (destinationType == typeof(string) && value is {t} id)");
            sb.AppendLine("            {");
            sb.AppendLine("                return id.ToString();");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine("            return base.ConvertTo(context, culture, value, destinationType);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            if (m.Namespace != null)
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }
    }
}
