using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CodeForge
{
    [Generator(LanguageNames.CSharp)]
    public sealed class EnumExtensionsGenerator : IIncrementalGenerator
    {
        internal const string AttributeName = "CodeForge.EnumExtensionsAttribute";

        private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace CodeForge
{
    [global::System.AttributeUsage(global::System.AttributeTargets.Enum, Inherited = false, AllowMultiple = false)]
    internal sealed class EnumExtensionsAttribute : global::System.Attribute
    {
    }
}
";

        internal sealed record EnumMember(string Name, string Value, string Description);

        internal sealed record EnumModel(
            string? Namespace,
            string Name,
            string Accessibility,
            string Underlying,
            EquatableArray<EnumMember> Members,
            EquatableArray<DiagnosticInfo> Diagnostics);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx => ctx.AddSource("EnumExtensionsAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

            var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeName,
                static (node, _) => node is EnumDeclarationSyntax,
                static (ctx, ct) => Transform(ctx, ct));

            context.RegisterSourceOutput(models, static (spc, model) =>
            {
                foreach (var d in model.Diagnostics)
                {
                    spc.ReportDiagnostic(d.ToDiagnostic());
                }

                if (model.Diagnostics.Length > 0)
                {
                    return;
                }

                var hint = (model.Namespace is null ? model.Name : model.Namespace + "." + model.Name) + ".EnumExtensions.g.cs";
                spc.AddSource(hint, SourceText.From(Emit(model), Encoding.UTF8));
            });
        }

        private static EnumModel Transform(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            var symbol = (INamedTypeSymbol)ctx.TargetSymbol;
            var syntax = (EnumDeclarationSyntax)ctx.TargetNode;
            var diagnostics = new List<DiagnosticInfo>();
            if (symbol.ContainingType != null)
            {
                diagnostics.Add(DiagnosticInfo.Create("CFG003", $"'{symbol.Name}' must be a top-level enum; nested enums are not supported.", syntax.Identifier.GetLocation()));
            }

            var members = new List<EnumMember>();
            foreach (var field in symbol.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
            {
                var description = field.Name;
                foreach (var attribute in field.GetAttributes())
                {
                    if (attribute.AttributeClass?.ToDisplayString() == "System.ComponentModel.DescriptionAttribute"
                        && attribute.ConstructorArguments.Length == 1
                        && attribute.ConstructorArguments[0].Value is string text)
                    {
                        description = text;
                    }
                }

                members.Add(new EnumMember(field.Name, System.Convert.ToString(field.ConstantValue, System.Globalization.CultureInfo.InvariantCulture) ?? "0", description));
            }

            return new EnumModel(
                symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString(),
                symbol.Name,
                symbol.DeclaredAccessibility == Accessibility.Public ? "public" : "internal",
                symbol.EnumUnderlyingType?.ToDisplayString() ?? "int",
                new EquatableArray<EnumMember>(members),
                new EquatableArray<DiagnosticInfo>(diagnostics));
        }

        private static string Quote(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

        private static string Emit(EnumModel m)
        {
            var e = m.Name;
            var distinct = m.Members.GroupBy(x => x.Value).Select(g => g.First()).ToList();
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            if (m.Namespace != null)
            {
                sb.AppendLine("namespace " + m.Namespace);
                sb.AppendLine("{");
            }

            sb.AppendLine($"{m.Accessibility} static class {e}Extensions");
            sb.AppendLine("{");

            sb.AppendLine($"    public static string ToStringFast(this {e} value) => value switch");
            sb.AppendLine("    {");
            foreach (var member in distinct)
            {
                sb.AppendLine($"        {e}.{member.Name} => {Quote(member.Name)},");
            }

            sb.AppendLine("        _ => value.ToString(),");
            sb.AppendLine("    };");
            sb.AppendLine();

            sb.AppendLine($"    public static string ToDescription(this {e} value) => value switch");
            sb.AppendLine("    {");
            foreach (var member in distinct)
            {
                sb.AppendLine($"        {e}.{member.Name} => {Quote(member.Description)},");
            }

            sb.AppendLine("        _ => value.ToString(),");
            sb.AppendLine("    };");
            sb.AppendLine();

            sb.AppendLine($"    public static bool IsDefinedFast(this {e} value) => value switch");
            sb.AppendLine("    {");
            if (distinct.Count > 0)
            {
                sb.AppendLine("        " + string.Join(" or ", distinct.Select(x => $"{e}.{x.Name}")) + " => true,");
            }

            sb.AppendLine("        _ => false,");
            sb.AppendLine("    };");
            sb.AppendLine();

            sb.AppendLine($"    public static bool TryParseFast(string? name, bool ignoreCase, out {e} value)");
            sb.AppendLine("    {");
            sb.AppendLine("        var comparison = ignoreCase ? global::System.StringComparison.OrdinalIgnoreCase : global::System.StringComparison.Ordinal;");
            foreach (var member in m.Members)
            {
                sb.AppendLine($"        if (string.Equals(name, {Quote(member.Name)}, comparison))");
                sb.AppendLine("        {");
                sb.AppendLine($"            value = {e}.{member.Name};");
                sb.AppendLine("            return true;");
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            sb.AppendLine("        value = default;");
            sb.AppendLine("        return false;");
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine("    public static string[] GetNames() => new[]");
            sb.AppendLine("    {");
            foreach (var member in m.Members)
            {
                sb.AppendLine($"        {Quote(member.Name)},");
            }

            sb.AppendLine("    };");
            sb.AppendLine();

            sb.AppendLine($"    public static {e}[] GetValues() => new[]");
            sb.AppendLine("    {");
            foreach (var member in m.Members)
            {
                sb.AppendLine($"        {e}.{member.Name},");
            }

            sb.AppendLine("    };");
            sb.AppendLine("}");
            if (m.Namespace != null)
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }
    }
}
