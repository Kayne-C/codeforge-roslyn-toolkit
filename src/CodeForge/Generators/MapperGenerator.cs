using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CodeForge
{
    [Generator(LanguageNames.CSharp)]
    public sealed class MapperGenerator : IIncrementalGenerator
    {
        internal const string AttributeName = "CodeForge.MapToAttribute";

        private const string AttributeSource = @"// <auto-generated/>
#nullable enable
namespace CodeForge
{
    [global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Struct, Inherited = false, AllowMultiple = true)]
    internal sealed class MapToAttribute : global::System.Attribute
    {
        public MapToAttribute(global::System.Type destination)
        {
            Destination = destination;
        }

        public global::System.Type Destination { get; }
    }

    [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Field, Inherited = false, AllowMultiple = false)]
    internal sealed class MapIgnoreAttribute : global::System.Attribute
    {
    }

    [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Field, Inherited = false, AllowMultiple = false)]
    internal sealed class MapPropertyAttribute : global::System.Attribute
    {
        public MapPropertyAttribute(string destinationName)
        {
            DestinationName = destinationName;
        }

        public string DestinationName { get; }
    }
}
";

        internal sealed record MapperModel(
            string? Namespace,
            string SourceName,
            string SourceDisplay,
            string Accessibility,
            bool SourceIsReference,
            EquatableArray<string> Methods,
            EquatableArray<DiagnosticInfo> Diagnostics);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx => ctx.AddSource("MapToAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8)));

            var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (ctx, ct) => Transform(ctx, ct));

            context.RegisterSourceOutput(models, static (spc, model) =>
            {
                foreach (var d in model.Diagnostics)
                {
                    spc.ReportDiagnostic(d.ToDiagnostic());
                }

                if (model.Methods.Length == 0)
                {
                    return;
                }

                spc.AddSource(HintName(model), SourceText.From(Emit(model), Encoding.UTF8));
            });
        }

        private static string HintName(MapperModel m) => (m.Namespace is null ? m.SourceName : m.Namespace + "." + m.SourceName) + ".Mapping.g.cs";

        internal static string ExtensionClassName(INamedTypeSymbol source) => source.Name + "MappingExtensions";

        internal static string MethodName(INamedTypeSymbol destination) => "To" + destination.Name;

        private static MapperModel Transform(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            var source = (INamedTypeSymbol)ctx.TargetSymbol;
            var syntax = (TypeDeclarationSyntax)ctx.TargetNode;
            var diagnostics = new List<DiagnosticInfo>();
            var methods = new List<string>();
            var compilation = ctx.SemanticModel.Compilation;

            if (source.ContainingType != null)
            {
                diagnostics.Add(DiagnosticInfo.Create("CFG104", $"'{source.Name}' must be a top-level type to declare mappings.", syntax.Identifier.GetLocation()));
            }
            else
            {
                foreach (var attribute in ctx.Attributes)
                {
                    ct.ThrowIfCancellationRequested();
                    if (attribute.ConstructorArguments.Length != 1 || !(attribute.ConstructorArguments[0].Value is INamedTypeSymbol destination) || destination.TypeKind == TypeKind.Error)
                    {
                        continue;
                    }

                    var location = attribute.ApplicationSyntaxReference?.GetSyntax(ct).GetLocation() ?? syntax.Identifier.GetLocation();
                    var builder = new MethodBuilder(compilation, source, destination, location, diagnostics);
                    var method = builder.Build();
                    if (method != null)
                    {
                        methods.Add(method);
                    }
                }
            }

            return new MapperModel(
                source.ContainingNamespace.IsGlobalNamespace ? null : source.ContainingNamespace.ToDisplayString(),
                source.Name,
                source.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                source.DeclaredAccessibility == Accessibility.Public ? "public" : "internal",
                !source.IsValueType,
                new EquatableArray<string>(methods),
                new EquatableArray<DiagnosticInfo>(diagnostics));
        }

        private static string Emit(MapperModel m)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            if (m.Namespace != null)
            {
                sb.AppendLine("namespace " + m.Namespace);
                sb.AppendLine("{");
            }

            sb.AppendLine($"{m.Accessibility} static class {m.SourceName}MappingExtensions");
            sb.AppendLine("{");
            sb.AppendLine(string.Join("\n\n", m.Methods));
            sb.AppendLine("}");
            if (m.Namespace != null)
            {
                sb.AppendLine("}");
            }

            return sb.ToString();
        }

        private sealed class MethodBuilder
        {
            private static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
                SymbolDisplayMiscellaneousOptions.UseSpecialTypes | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

            private readonly Compilation _compilation;
            private readonly INamedTypeSymbol _source;
            private readonly INamedTypeSymbol _destination;
            private readonly Location _location;
            private readonly List<DiagnosticInfo> _diagnostics;
            private int _lambda;

            public MethodBuilder(Compilation compilation, INamedTypeSymbol source, INamedTypeSymbol destination, Location location, List<DiagnosticInfo> diagnostics)
            {
                _compilation = compilation;
                _source = source;
                _destination = destination;
                _location = location;
                _diagnostics = diagnostics;
            }

            private static bool IsReadableMember(ISymbol s) =>
                !s.IsStatic && s.DeclaredAccessibility == Accessibility.Public && !s.IsImplicitlyDeclared
                && ((s is IPropertySymbol p && p.GetMethod != null && !p.IsIndexer) || s is IFieldSymbol f && !f.IsConst);

            private static ITypeSymbol TypeOf(ISymbol member) => member is IPropertySymbol p ? p.Type : ((IFieldSymbol)member).Type;

            private static bool HasAttribute(ISymbol member, string name) => member.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == name);

            private static string? RenamedTo(ISymbol member)
            {
                var attribute = member.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "CodeForge.MapPropertyAttribute");
                return attribute != null && attribute.ConstructorArguments.Length == 1 ? attribute.ConstructorArguments[0].Value as string : null;
            }

            private void Report(string id, string message) => _diagnostics.Add(DiagnosticInfo.Create(id, message, _location));

            public string? Build()
            {
                var sourceMembers = new Dictionary<string, ISymbol>(StringComparer.OrdinalIgnoreCase);
                foreach (var member in AllMembers(_source).Where(IsReadableMember))
                {
                    if (HasAttribute(member, "CodeForge.MapIgnoreAttribute"))
                    {
                        continue;
                    }

                    var key = RenamedTo(member) ?? member.Name;
                    if (!sourceMembers.ContainsKey(key))
                    {
                        sourceMembers[key] = member;
                    }
                }

                var constructor = ChooseConstructor(_destination, sourceMembers);
                if (constructor == null)
                {
                    Report("CFG104", $"'{_destination.Name}' has no accessible constructor that can be called when mapping from '{_source.Name}'.");
                    return null;
                }

                var failed = false;
                var arguments = new List<string>();
                var constructorNames = new HashSet<string>(constructor.Parameters.Select(p => p.Name), StringComparer.OrdinalIgnoreCase);
                foreach (var parameter in constructor.Parameters)
                {
                    if (sourceMembers.TryGetValue(parameter.Name, out var member))
                    {
                        var expression = Convert("source." + member.Name, TypeOf(member), parameter.Type, $"{_source.Name}.{member.Name} -> {_destination.Name}.{parameter.Name}", ref failed);
                        arguments.Add(parameter.Name + ": " + expression);
                    }
                    else if (!parameter.HasExplicitDefaultValue)
                    {
                        Report("CFG101", $"Constructor parameter '{_destination.Name}.{parameter.Name}' has no matching member on '{_source.Name}'.");
                        failed = true;
                    }
                }

                var initializers = new List<string>();
                foreach (var member in AllMembers(_destination))
                {
                    if (member.IsStatic || member.DeclaredAccessibility != Accessibility.Public || constructorNames.Contains(member.Name))
                    {
                        continue;
                    }

                    ITypeSymbol? type = null;
                    var required = false;
                    if (member is IPropertySymbol property && property.SetMethod != null && !property.IsIndexer
                        && property.SetMethod.DeclaredAccessibility == Accessibility.Public)
                    {
                        type = property.Type;
                        required = property.IsRequired;
                    }
                    else if (member is IFieldSymbol field && !field.IsReadOnly && !field.IsConst)
                    {
                        type = field.Type;
                        required = field.IsRequired;
                    }

                    if (type == null || HasAttribute(member, "CodeForge.MapIgnoreAttribute"))
                    {
                        continue;
                    }

                    if (sourceMembers.TryGetValue(member.Name, out var sourceMember))
                    {
                        var expression = Convert("source." + sourceMember.Name, TypeOf(sourceMember), type, $"{_source.Name}.{sourceMember.Name} -> {_destination.Name}.{member.Name}", ref failed);
                        initializers.Add($"{member.Name} = {expression}");
                    }
                    else if (required)
                    {
                        Report("CFG101", $"Required member '{_destination.Name}.{member.Name}' has no matching member on '{_source.Name}'.");
                        failed = true;
                    }
                    else
                    {
                        Report("CFG101", $"'{_destination.Name}.{member.Name}' has no matching member on '{_source.Name}'; it keeps its default value. Add [MapIgnore] to silence this.");
                    }
                }

                if (failed)
                {
                    return null;
                }

                var destinationName = _destination.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var sourceName = _source.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var sb = new StringBuilder();
                sb.AppendLine($"    public static {destinationName} {MethodName(_destination)}(this {sourceName} source)");
                sb.AppendLine("    {");
                if (!_source.IsValueType)
                {
                    sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(source);");
                }

                sb.Append($"        return new {destinationName}(" + string.Join(", ", arguments) + ")");
                if (initializers.Count > 0)
                {
                    sb.AppendLine();
                    sb.AppendLine("        {");
                    foreach (var initializer in initializers)
                    {
                        sb.AppendLine($"            {initializer},");
                    }

                    sb.Append("        }");
                }

                sb.AppendLine(";");
                sb.Append("    }");
                return sb.ToString();
            }

            private static IEnumerable<ISymbol> AllMembers(INamedTypeSymbol type)
            {
                for (var t = (ITypeSymbol?)type; t != null && t.SpecialType != SpecialType.System_Object && t.SpecialType != SpecialType.System_ValueType; t = t.BaseType)
                {
                    foreach (var member in t.GetMembers())
                    {
                        yield return member;
                    }
                }
            }

            private static IMethodSymbol? ChooseConstructor(INamedTypeSymbol destination, Dictionary<string, ISymbol> sourceMembers)
            {
                var candidates = destination.InstanceConstructors
                    .Where(c => c.DeclaredAccessibility == Accessibility.Public && !c.IsImplicitlyDeclared || c.DeclaredAccessibility == Accessibility.Public && c.Parameters.Length == 0)
                    .Where(c => !(c.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(c.Parameters[0].Type, destination)))
                    .ToList();
                if (candidates.Count == 0 && destination.IsValueType)
                {
                    return null;
                }

                return candidates
                    .OrderByDescending(c => c.Parameters.Count(p => sourceMembers.ContainsKey(p.Name)) - (c.Parameters.Count(p => !sourceMembers.ContainsKey(p.Name) && !p.HasExplicitDefaultValue) * 100))
                    .ThenByDescending(c => c.Parameters.Length)
                    .FirstOrDefault();
            }

            private string Convert(string expression, ITypeSymbol from, ITypeSymbol to, string path, ref bool failed)
            {
                var fromText = from.ToDisplayString(Full);
                var toText = to.ToDisplayString(Full);

                var fromUnderlying = NullableUnderlying(from);
                var toUnderlying = NullableUnderlying(to);
                var fromIsNullableValue = from.IsValueType && from.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
                var toIsNullableValue = to.IsValueType && to.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
                var fromMayBeNull = fromIsNullableValue || (!from.IsValueType && from.NullableAnnotation == NullableAnnotation.Annotated);
                var toAllowsNull = toIsNullableValue || (!to.IsValueType && to.NullableAnnotation != NullableAnnotation.NotAnnotated);

                if (fromMayBeNull && !toAllowsNull)
                {
                    Report("CFG103", $"{path}: the source is nullable ('{fromText}') but the destination is not ('{toText}').");
                }

                if (SymbolEqualityComparer.Default.Equals(fromUnderlying, toUnderlying) && !(fromIsNullableValue && !toIsNullableValue))
                {
                    return expression;
                }

                if (fromIsNullableValue && !toIsNullableValue)
                {
                    return SymbolEqualityComparer.Default.Equals(fromUnderlying, toUnderlying)
                        ? $"{expression}.GetValueOrDefault()"
                        : Convert($"{expression}.GetValueOrDefault()", fromUnderlying, to, path, ref failed);
                }

                if (fromUnderlying.TypeKind == TypeKind.Enum && toUnderlying.TypeKind == TypeKind.Enum)
                {
                    var names = ((INamedTypeSymbol)fromUnderlying).GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue).Select(f => f.Name + "=" + f.ConstantValue).OrderBy(n => n);
                    var otherNames = ((INamedTypeSymbol)toUnderlying).GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue).Select(f => f.Name + "=" + f.ConstantValue).OrderBy(n => n);
                    if (names.SequenceEqual(otherNames))
                    {
                        return fromMayBeNull ? $"{expression} is {{ }} value ? ({toUnderlying.ToDisplayString(Full)})value : default" : $"({toText}){expression}";
                    }

                    Report("CFG102", $"{path}: enums '{fromText}' and '{toText}' have different members and cannot be mapped.");
                    failed = true;
                    return "default!";
                }

                var conversion = _compilation.ClassifyConversion(fromUnderlying, toUnderlying);
                if (conversion.IsImplicit && conversion.IsNumeric)
                {
                    return expression;
                }

                if (HasMapping(fromUnderlying, toUnderlying, out var call))
                {
                    if (fromMayBeNull)
                    {
                        return toAllowsNull ? $"{expression} is null ? default : {call}({expression})" : $"{call}({expression}!)";
                    }

                    return $"{call}({expression})";
                }

                if (TryElementTypes(fromUnderlying, out var fromElement) && TryElementTypes(toUnderlying, out var toElement))
                {
                    var parameter = "e" + (_lambda++);
                    var nested = false;
                    var inner = Convert(parameter, fromElement, toElement, path + "[]", ref nested);
                    failed |= nested;
                    var materialize = CollectionKind(toUnderlying);
                    var selected = inner == parameter
                        ? expression
                        : $"global::System.Linq.Enumerable.Select({expression}, {parameter} => {inner})";
                    var result = materialize switch
                    {
                        "array" => $"global::System.Linq.Enumerable.ToArray({selected})",
                        "list" => $"global::System.Linq.Enumerable.ToList({selected})",
                        _ => selected,
                    };
                    return fromMayBeNull ? (toAllowsNull ? $"{expression} is null ? default : {result}" : $"{result}") : result;
                }

                if (conversion.IsImplicit && (conversion.IsReference || conversion.IsIdentity || conversion.IsBoxing))
                {
                    return expression;
                }

                Report("CFG102", $"{path}: cannot map '{fromText}' to '{toText}'. Add a [MapTo] mapping between the types or [MapIgnore] the member.");
                failed = true;
                return "default!";
            }

            private static ITypeSymbol NullableUnderlying(ITypeSymbol type) =>
                type.IsValueType && type is INamedTypeSymbol named && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
                    ? named.TypeArguments[0]
                    : type.WithNullableAnnotation(NullableAnnotation.NotAnnotated);

            private bool HasMapping(ITypeSymbol from, ITypeSymbol to, out string call)
            {
                call = string.Empty;
                if (!(from is INamedTypeSymbol source) || !(to is INamedTypeSymbol destination))
                {
                    return false;
                }

                foreach (var attribute in source.GetAttributes())
                {
                    if (attribute.AttributeClass?.ToDisplayString() == AttributeName
                        && attribute.ConstructorArguments.Length == 1
                        && SymbolEqualityComparer.Default.Equals(attribute.ConstructorArguments[0].Value as INamedTypeSymbol, destination))
                    {
                        var ns = source.ContainingNamespace.IsGlobalNamespace ? "global::" : "global::" + source.ContainingNamespace.ToDisplayString() + ".";
                        call = ns + ExtensionClassName(source) + "." + MethodName(destination);
                        return true;
                    }
                }

                return false;
            }

            private static bool TryElementTypes(ITypeSymbol type, out ITypeSymbol element)
            {
                element = type;
                if (type is IArrayTypeSymbol array && array.Rank == 1)
                {
                    element = array.ElementType;
                    return true;
                }

                if (type is INamedTypeSymbol named && named.IsGenericType && named.TypeArguments.Length == 1)
                {
                    switch (named.OriginalDefinition.ToDisplayString())
                    {
                        case "System.Collections.Generic.List<T>":
                        case "System.Collections.Generic.IEnumerable<T>":
                        case "System.Collections.Generic.IReadOnlyList<T>":
                        case "System.Collections.Generic.IReadOnlyCollection<T>":
                        case "System.Collections.Generic.IList<T>":
                        case "System.Collections.Generic.ICollection<T>":
                            element = named.TypeArguments[0];
                            return true;
                    }
                }

                return false;
            }

            private static string CollectionKind(ITypeSymbol type)
            {
                if (type is IArrayTypeSymbol)
                {
                    return "array";
                }

                var name = ((INamedTypeSymbol)type).OriginalDefinition.ToDisplayString();
                return name == "System.Collections.Generic.IEnumerable<T>" ? "sequence" : "list";
            }
        }
    }
}
